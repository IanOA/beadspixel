const LANG_LABELS = {
  "zh-TW": "繁體中文",
  "zh-CN": "简体中文",
  "en": "English",
  "ja": "日本語",
  "ko": "한국어"
};

function getLang() {
  return localStorage.getItem('bead-lang') || 'zh-TW';
}

function setLang(lang) {
  localStorage.setItem('bead-lang', lang);
  applyLang(lang);
}

function t(key) {
  var lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || (I18N['zh-TW'][key]) || key;
}

function applyLang(lang) {
  if (!lang) lang = getLang();
  var dict = I18N[lang] || I18N['zh-TW'];
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' && el.type !== 'checkbox') {
        el.placeholder = dict[key];
      } else if (el.tagName === 'OPTION') {
        el.textContent = dict[key];
      } else {
        el.innerHTML = dict[key];
      }
    }
  });
  // Update html lang
  document.documentElement.lang = lang === 'zh-TW' ? 'zh-TW' : lang === 'zh-CN' ? 'zh-CN' : lang;
  // Update lang selector display
  var sel = document.getElementById('langSelect');
  if (sel) sel.value = lang;
}

// Build language selector HTML
function buildLangSelector() {
  var current = getLang();
  var html = '<select id="langSelect" class="lang-select" aria-label="Language">';
  for (var code in LANG_LABELS) {
    html += '<option value="' + code + '"' + (code === current ? ' selected' : '') + '>' + LANG_LABELS[code] + '</option>';
  }
  html += '</select>';
  return html;
}

// Auto-init on load
document.addEventListener('DOMContentLoaded', function() {
  // Insert lang selector into nav or header
  var navInner = document.querySelector('.nav-inner');
  var header = document.querySelector('header');
  if (navInner) {
    var div = document.createElement('div');
    div.className = 'lang-wrap';
    div.innerHTML = buildLangSelector();
    navInner.appendChild(div);
  } else if (header) {
    var div = document.createElement('div');
    div.className = 'lang-wrap-header';
    div.innerHTML = buildLangSelector();
    header.appendChild(div);
  }
  // Bind change
  var sel = document.getElementById('langSelect');
  if (sel) sel.addEventListener('change', function() { setLang(this.value); });
  // Apply
  applyLang(getLang());

  // ===== Animated Logo =====
  var logoCanvases = document.querySelectorAll('.logo-canvas');
  if (logoCanvases.length) {
    var logoHeart = [
      [0,1,0,1,0],
      [1,2,3,2,1],
      [1,3,3,3,1],
      [0,1,3,1,0],
      [0,0,1,0,0]
    ];
    var logoStar = [
      [0,0,1,0,0],
      [0,1,2,1,0],
      [1,2,3,2,1],
      [0,1,2,1,0],
      [0,0,1,0,0]
    ];
    var logoPatterns = [logoHeart, logoStar];
    var logoPals = [
      ['#faf7f2','#ffccd5','#ff8fa3','#f06449'],
      ['#faf7f2','#c1f0db','#36c9a7','#0a8967'],
      ['#faf7f2','#d5c4f7','#9b7bf7','#6a3fd4'],
      ['#faf7f2','#ffe5a0','#ffc53d','#e6a200']
    ];
    var logoIdx = 0;

    function drawLogo() {
      // Sync with landing page demo if available
      var i = (typeof window._beadDemoIdx === 'number') ? window._beadDemoIdx : logoIdx;
      var pal = logoPals[i % logoPals.length];
      var pat = logoPatterns[i % logoPatterns.length];
      logoCanvases.forEach(function(c) {
        var s = c.width;
        var ctx = c.getContext('2d');
        var cell = s / 5;
        var r = cell * 0.38;
        // Background
        ctx.clearRect(0, 0, s, s);
        ctx.fillStyle = pal[0];
        ctx.beginPath();
        var rr = s * 0.18;
        ctx.moveTo(rr, 0);
        ctx.lineTo(s - rr, 0); ctx.quadraticCurveTo(s, 0, s, rr);
        ctx.lineTo(s, s - rr); ctx.quadraticCurveTo(s, s, s - rr, s);
        ctx.lineTo(rr, s); ctx.quadraticCurveTo(0, s, 0, s - rr);
        ctx.lineTo(0, rr); ctx.quadraticCurveTo(0, 0, rr, 0);
        ctx.closePath();
        ctx.fill();
        // Beads
        for (var y = 0; y < 5; y++) {
          for (var x = 0; x < 5; x++) {
            var v = pat[y][x];
            if (v === 0) continue;
            ctx.beginPath();
            ctx.arc(x * cell + cell / 2, y * cell + cell / 2, r, 0, Math.PI * 2);
            ctx.fillStyle = pal[v];
            ctx.fill();
          }
        }
      });
      logoIdx++;
    }

    drawLogo();
    setInterval(drawLogo, 3500);
  }
});
